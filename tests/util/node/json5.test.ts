import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

import JSON5 from "json5"
import { afterEach, describe, expect, test } from "vite-plus/test"

import { json5Edited, keepingComments, keepingCommentsIn, readJSON5File } from "spell/util/node/json5"

/**
 * JSON5 written with its comments kept (`spell/util/node/json5`):  spaces' files, and the component sets' site data
 * (`docs/__data/*.json5`, epic `epic-workflow` P20), whose writers rewrite the whole file on every run.
 */

/** Temporary folders, removed after each case. */
const made: string[] = []

afterEach(() => {
  for (const folder of made.splice(0)) rmSync(folder, { recursive: true, force: true })
})

/** A new temporary folder. */
function folder(): string {
  const dir = mkdtempSync(join(tmpdir(), "assembler-json5-"))
  made.push(dir)
  return dir
}

/** A search file as Spell UI's writer lays it out:  one section per line (`SiteSearchBuilder.text()`). */
const SEARCH = `{
  "$comment": "GENERATED by \`yarn site:data\` -- do not edit.",
  "pages": [
    {
      "path": "index.html",
      "title": "Spell UI",
      "sections": [
        {"id":"design","title":"Design"},
        {"id":"theming","title":"Theming"}
      ]
    }
  ]
}
`

/** `SEARCH` with a comment written into it by hand. */
const COMMENTED = SEARCH.replace(`    {\n      "path"`, `    // the home page:  always first\n    {\n      "path"`)

describe("json5Edited()", () => {
  test("keeps every comment, and every key the value keeps, where it was", () => {
    const source = '{\n  // who\n  "name": "Owen", // first name\n  "age": 50\n}\n'
    expect(json5Edited(source, { name: "O", age: 50 })).toBe(
      '{\n  // who\n  "name": "O", // first name\n  "age": 50\n}\n'
    )
  })

  test("a null is written as null, at any depth (I22)", () => {
    const source = '{\n  // who listens\n  "listening": "a",\n  "marks": { "j1": "x" }\n}\n'
    const edited = json5Edited(source, { listening: null, marks: { j1: null } })
    expect(edited).toContain("// who listens")
    expect(JSON5.parse(edited)).toEqual({ listening: null, marks: { j1: null } })
  })

  test("a removed key takes the comments above and beside it;  the others stay", () => {
    const source = '{\n  // above a\n  "a": 1, // beside a\n  // above b\n  "b": 2, // beside b\n  "c": 3\n}\n'
    expect(json5Edited(source, { a: 1, c: 3 })).toBe('{\n  // above a\n  "a": 1, // beside a\n  "c": 3\n}\n')
  })

  test("the last key removed:  the comma before it goes, the comment beside that stays", () => {
    expect(json5Edited('{\n  "a": 1, // why\n  "b": 2\n}\n', { a: 1 })).toBe('{\n  "a": 1 // why\n}\n')
  })

  test("a new key goes last, after the comment beside the old last, which gets a comma", () => {
    expect(json5Edited('{\n  "a": 1 // why\n}\n', { a: 1, b: { c: [2] } })).toBe(
      '{\n  "a": 1, // why\n  "b": {\n    "c": [\n      2\n    ]\n  }\n}\n'
    )
  })

  test("an object on one line stays on one line", () => {
    expect(json5Edited('{ "a": 1, "b": 2 }', { a: 5, c: [1] })).toBe('{ "a": 5, "c": [1] }\n')
  })

  test("an array is matched by position:  items past the new length go, new ones are added", () => {
    expect(json5Edited("[\n  // one\n  1,\n  // two\n  2\n]\n", [9])).toBe("[\n  // one\n  9\n]\n")
    expect(json5Edited("[\n  // one\n  1\n]\n", [1, 2])).toBe("[\n  // one\n  1,\n  2\n]\n")
  })

  test("everything removed:  empty, unless a comment of its own stays", () => {
    expect(json5Edited('{\n  "a": 1\n}\n', {})).toBe("{}\n")
    expect(json5Edited('{\n  "a": 1\n  // the end of it\n}\n', {})).toBe("{\n  // the end of it\n}\n")
    expect(json5Edited('{\n  "a": 1\n  // the end of it\n}\n', { b: 2 })).toBe('{\n  // the end of it\n  "b": 2\n}\n')
  })

  test("what didn't change keeps its exact text:  quotes, unquoted keys, a trailing comma", () => {
    const source = "{\n  name: 'Owen', // who\n  'age': +50,\n}\n"
    expect(json5Edited(source, { name: "Owen", age: 50 })).toBe(source)
    expect(json5Edited(source, { name: "O", age: 50 })).toBe("{\n  name: \"O\", // who\n  'age': +50,\n}\n")
  })

  test("text that looks like a comment, or holds brackets and quotes, is only text", () => {
    const source = '{\n  // real\n  "a // no": "b /* no */ } ] \\" still"\n}\n'
    expect(json5Edited(source, { "a // no": "c" })).toBe('{\n  // real\n  "a // no": "c"\n}\n')
  })

  test("a key holding undefined is left as it was;  a value's toJSON() is what's written", () => {
    expect(json5Edited('{\n  // c\n  "a": 1\n}', { a: undefined, b: 2 })).toBe('{\n  // c\n  "a": 1,\n  "b": 2\n}\n')
    expect(JSON5.parse(json5Edited('{\n  // c\n  "a": 1\n}', { a: new Date(0) }))).toEqual({
      a: "1970-01-01T00:00:00.000Z"
    })
  })

  test("text that won't read as JSON5 throws a SyntaxError", () => {
    expect(() => json5Edited("{ // broken\n", {})).toThrow(SyntaxError)
  })

  test("an empty source:  the value alone, two-space indented", () => {
    expect(json5Edited("", { a: [1] })).toBe('{\n  "a": [\n    1\n  ]\n}\n')
  })
})

describe("keepingComments()", () => {
  test("plain JSON before:  the generator's own text, its layout too", () => {
    const text = SEARCH.replace('"Theming"', '"Themes"')
    expect(keepingComments(SEARCH, text)).toBe(text)
    expect(keepingComments("", text)).toBe(text)
  })

  test("a comment written by hand survives the generator's next write, with the value it wrote", () => {
    const written = keepingComments(COMMENTED, SEARCH.replace('"Theming"', '"Themes"'))
    expect(written).toContain("// the home page:  always first")
    expect(written).toContain('{"id":"theming","title":"Themes"}')
    expect(written.replace('"Themes"', '"Theming"')).toBe(COMMENTED)
  })

  test("a value that didn't change leaves the file as it was:  a `--check` stays quiet", () => {
    expect(keepingComments(COMMENTED, SEARCH)).toBe(COMMENTED)
  })
})

describe("keepingCommentsIn()", () => {
  test("reads the file there:  its comments kept;  none yet, the text as it is", () => {
    const dir = folder()
    const file = join(dir, "search.json5")
    expect(keepingCommentsIn(file, SEARCH)).toBe(SEARCH)
    writeFileSync(file, COMMENTED)
    expect(keepingCommentsIn(file, SEARCH.replace('"Design"', '"Designs"'))).toContain("// the home page")
  })

  test("leaves a file that isn't `.json5` alone:  `text` as it is", () => {
    const file = join(folder(), "custom-elements.json")
    writeFileSync(file, "// not JSON\n{}\n")
    expect(keepingCommentsIn(file, "{}\n")).toBe("{}\n")
  })

  test("names the file when it holds JSON5 that won't read", () => {
    const file = join(folder(), "pages.json5")
    writeFileSync(file, "{ // broken\n")
    expect(() => keepingCommentsIn(file, "{}\n")).toThrow(/pages\.json5:/)
  })
})

describe("readJSON5File()", () => {
  test("reads JSON5, comments and all;  names the file when it won't read", () => {
    const dir = folder()
    writeFileSync(join(dir, "a.json5"), COMMENTED)
    expect(readJSON5File<{ pages: { path: string }[] }>(join(dir, "a.json5")).pages[0]!.path).toBe("index.html")
    writeFileSync(join(dir, "b.json5"), "{ nope")
    expect(() => readJSON5File(join(dir, "b.json5"))).toThrow(/b\.json5:/)
    expect(readFileSync(join(dir, "a.json5"), "utf8")).toBe(COMMENTED)
  })
})
