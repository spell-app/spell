/**
 * `tsx scripts/class-phrases.ts [--check]`:  ONE-TIME rewrite of every substring class selector in the family CSS
 * (`[class*="bottom attached"]`) into a plain class word (`.bottom-attached`), and the list of those phrases,
 * `src/elements/ClassPhrases.ts`, which `ClassBuilder.withPhrases()` writes the joined words from
 * (epic `solid-2-final` P5).
 * - Why:  a substring match is the slowest selector there is;  a class word is the fastest.
 * - The mapping:
 *   - a phrase of words (`bottom attached`, `two wide computer`) => its joined word (`.bottom-attached`)
 *   - `" only"` => `.only`, `"aligned"` => `.aligned`:  whole class words already
 *   - an aspect ratio (`4:3`) => that class word, escaped (`.\34 \:3`)
 *   - anything else:  refused, naming the file and the selector
 * - Left as they are:  the selectors for a PAGE's own markup, which no builder writes, so it has no joined words
 *   (`MARKUP_SHEETS`, written into the list's file for the test to read):
 *   - a sheet that also styles the page's light DOM (`<ui-table>`'s, whose `<td class="right aligned">` a page writes)
 *   - a substring inside `::slotted()`:  the page's own children
 * - Run once, kept for a family brought over from Fomantic later:  `tests/elements/ClassPhrases.test.ts` fails on
 *   any substring selector left in a family sheet.
 * - The phrase list MERGES:  a phrase already in it stays while some sheet still styles its joined word,
 *   so a second run (with no substring selectors left) keeps every one in use, and drops the rest.
 * - `--check`:  write nothing;  exit 1 if a sheet still has one.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { parseArgs } from "node:util"

import { Terminal } from "spell/element-tools/Terminal"
import { writeOrCheck } from "spell/element-tools/generatedFiles"

import { CLASS_PHRASES } from "spell/ui/elements/ClassPhrases"
import { formatted } from "spell/ui/tools/generatedFiles"

/** `src/components/`:  every family's sheets. */
const COMPONENTS = fileURLToPath(new URL("../src/components/", import.meta.url))

/** The phrase list this writes. */
const PHRASES_FILE = fileURLToPath(new URL("../src/elements/ClassPhrases.ts", import.meta.url))

/** A substring class selector, its text captured;  and whether it's inside `::slotted()`, the page's own markup. */
const SUBSTRING_SELECTOR = /(::slotted\()?\[class\*="([^"]*)"\]/g

/** Sheets that also style a page's own markup, left as they are, each with why (paths under `components/`). */
const MARKUP_SHEETS: Record<string, string> = {
  "ui-table/UITable.css": "also the page's sheet for its light-DOM table, whose cells the page writes"
}

/** A phrase of class words:  lowercase words, one space between. */
const WORD_PHRASE = /^[a-z]+( [a-z]+)+$/

/** An aspect-ratio word, `4:3`. */
const RATIO = /^\d+:\d+$/

/** Single class words written as substrings, which already are whole words in every class string. */
const WHOLE_WORDS: Record<string, string> = { " only": "only", aligned: "aligned" }

const { values } = parseArgs({ options: { check: { type: "boolean", default: false } } })
const phrases = new Set<string>(CLASS_PHRASES)
let rewritten = 0
const sheets = cssFiles(COMPONENTS)
for (const file of sheets) {
  if (MARKUP_SHEETS[path.relative(COMPONENTS, file)]) continue
  const css = fs.readFileSync(file, "utf8")
  const next = css.replace(SUBSTRING_SELECTOR, (selector, slotted: string | undefined, text: string) => {
    if (slotted) return selector
    rewritten++
    if (WORD_PHRASE.test(text)) {
      phrases.add(text)
      return `.${text.replaceAll(" ", "-")}`
    }
    if (WHOLE_WORDS[text]) return `.${WHOLE_WORDS[text]}`
    if (RATIO.test(text)) return `.${escapedClass(text)}`
    throw new TypeError(`class-phrases:  can't map ${selector} in ${path.relative(COMPONENTS, file)}`)
  })
  if (next !== css && !values.check) fs.writeFileSync(file, next)
}

const allCSS = sheets.map((file) => fs.readFileSync(file, "utf8")).join("\n")
const list = [...phrases]
  .filter((phrase) => new RegExp(`\\.${phrase.replaceAll(" ", "-")}(?![\\w-])`).test(allCSS))
  .sort()
const source = `/**
 * GENERATED by \`ui/scripts/class-phrases.ts\`:  Fomantic's class phrases of two or more words that the family CSS
 * styles, each as ONE joined class word (\`bottom attached\` => \`.bottom-attached\`;  epic \`solid-2-final\` P5).
 * - \`ClassBuilder.withPhrases()\` adds the joined word of every phrase a class string holds, as a substring:
 *   exactly what \`[class*="bottom attached"]\` matched before.
 * - A family sheet styles the joined word, never a substring:  \`tests/elements/ClassPhrases.test.ts\` checks.
 * - A new phrase:  add it here, by hand, in order.
 */
export const CLASS_PHRASES: readonly string[] = ${JSON.stringify(list)}

/** Sheets that also style a page's own markup, so keep their substring selectors, each with why (under \`components/\`). */
export const MARKUP_SHEETS: Readonly<Record<string, string>> = ${JSON.stringify(MARKUP_SHEETS)}
`
const stale = writeOrCheck(await formatted([[PHRASES_FILE, source]]), {
  command: "tsx scripts/class-phrases.ts",
  isCheck: values.check
})
Terminal.out(`class-phrases:  ${rewritten} substring selector(s) rewritten, ${list.length} phrase(s)`)
if (values.check && (rewritten || stale.length)) process.exitCode = 1

////////////////
// ## Helpers
////////////////

/** Every `.css` file under `folder`. */
function cssFiles(folder: string): string[] {
  return fs
    .readdirSync(folder, { recursive: true, encoding: "utf8" })
    .filter((name) => name.endsWith(".css"))
    .map((name) => path.join(folder, name))
}

/** `word` as a CSS class selector's escaped name:  a leading digit as its code point, `:` escaped. */
function escapedClass(word: string): string {
  return `\\3${word[0]} ${word.slice(1).replaceAll(":", "\\:")}`
}
