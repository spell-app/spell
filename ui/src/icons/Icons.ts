import {
  ICON_NAMES_ATTRIBUTE,
  type IconAliasMap,
  type IconData,
  type IconEntry,
  type IconNames,
  type IconNamesIndex,
  type IconResolved,
  type IconStyle
} from "./icons.types"

/** Namespace for SVG element creation -- `document.createElementNS()` needs it, `createElement()` doesn't apply. */
const SVG_NS = "http://www.w3.org/2000/svg"

/**
 * Shape of every Font Awesome name:  lowercase letters / digits, single dashes between words.
 * - Guards the computed glyph URL, now that a typed name reaches `import()` without the names index
 *   vouching for it first -- `"../../data/aliases"` never becomes a request.
 */
const GLYPH_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

/**
 * Runtime-side loader for Font Awesome 7 Free icon data generated by `scripts/gen-icons.ts`.
 * - Framework-agnostic:  every method works with plain data (`IconData` tuples) except `svg()`, the one
 *   place that touches the DOM.
 * - Static-only class (no instances) -- there's exactly one icon dataset per page, same shape as `UI`'s
 *   singleton services, but simple enough not to need `new`.
 * - ONE ES MODULE PER ICON (`glyphs/<style>/<name>.js`, `export default [w, h, "path"]`):  `get()` computes
 *   the URL from the resolved name and `import()`s it.  There is NO name -> loader map, so a bundler neither
 *   inlines the glyphs nor emits 2000 entries -- the glyph files just have to be served next to the built
 *   module (see `docs/icons.md`, "Shipping icons").  The module system is the cache:  a URL evaluates once
 *   per page, even across two bundles.
 * - GLYPH FIRST:  a style-less name is simply tried as `solid`, then `brands` -- the glyph request IS the
 *   existence check, so the common case loads no index at all.
 *   - solid icon ~== 1 request,  brand icon ~== 2 (a `solid` 404, then the brand)
 *   - trade-off:  a name that isn't an exact Font Awesome name costs 404s before its real answer --
 *     an alias (`setting`) 2, until the alias maps are cached;  an unknown name 2, plus the alias maps
 *     and (dashed names only) `names.json` for the word-order fallback.  Before, `names.json`
 *     (~9 KB gzip) was loaded up front so unknown names never hit the network.
 *   - every miss is cached (`#loadGlyph()`), so no URL is ever requested twice
 *   - never `regular` over the network:  every regular icon also exists in solid, so a style-less
 *     regular request could only 404.  `register()`ed regular icons are still found, from cache.
 * - `names.json` loads only for `names()`, `resolve()` and the word-order fallback -- after every direct
 *   attempt failed.  Once loaded, it vouches for names again:  no more 404s.
 * - The three alias maps are lazy too, loaded by the first name that isn't found as typed, and cached forever.
 * - `peek()` stays fully synchronous by only ever answering from what's ALREADY cached:  `undefined` for a
 *   name that needs an alias map or the names index before those have loaded, same as for an unloaded glyph.
 * - `register()` puts a statically imported glyph in the same cache, the tree-shakable path for apps that
 *   only use a few icons.
 */
export class Icons {
  /**
   * `<style>/<name>` -> that icon's load state, hits AND misses.
   * - Shared across every `get()` caller;  `register()` writes here too.
   */
  static #icons = new Map<string, IconEntry>()

  /**
   * Base URL of the `glyphs/` directory, if the files are NOT next to the built module.
   * - Empty (default) ~== `glyphs/` next to the module containing `Icons`, via `import.meta.url`.
   * - e.g. `Icons.glyphBase = "https://cdn.example.com/ui/glyphs/"`.  MUST end with `/`.
   * - Read on every load:  set it before the first `get()`.
   */
  static glyphBase = ""

  /** `names.json`, once loaded -- `undefined` until `names()`, `resolve()` or the word-order fallback asks. */
  static #namesLoader: Promise<IconNamesIndex> | undefined
  /**
   * `names.json` as `Set`s, built with it.
   * - Once present, `#lookup()` checks it before any `import()`, so a known-missing name costs nothing.
   */
  static #nameSets: Record<IconStyle, Set<string>> | undefined

  /** The three alias maps, once loaded -- `undefined` until the first lookup that needs one. */
  static #aliasesLoader: Promise<AliasMaps> | undefined
  static #aliases: AliasMaps | undefined

  /**
   * Sorted words -> the ONE icon they name in any order, or `null` if 2+ icons share them
   * (`arrow-up-a-z` / `arrow-up-z-a`).
   * - Built on first use from the solid names + Font Awesome's aliases -- see `#reorder()`.
   */
  static #wordSets: Map<string, string | null> | undefined

  ////////////////
  // ## Name resolution
  ////////////////

  /**
   * Resolves a possibly-aliased, possibly-multi-word icon name to its canonical Font Awesome 7 name + style.
   * - An introspection helper (tests, docs):  `get()` does NOT call it, and it always loads `names.json`
   *   (~9 KB gzip) plus the alias maps -- telling a bare `github` (brands) from `user` (solid) without
   *   requesting a glyph needs the full name lists.
   * - Answers what `get()` would load, except where `get()` answers from cache first:  a name
   *   `register()`ed as `regular`, or `font-awesome` / `web-awesome` (solid AND brands) cached as brands.
   * - Spaces ~== dashes:  `"tablet button"` ~== `"tablet-button"`,  `"sign-in"` ~== `"sign in"`.
   * - Order:  strip a trailing `outline` word (-> `style: "regular"`), then Fomantic's OWN alias vocabulary
   *   (`"mail"` -> `"envelope"`, `"setting"` -> `"gear"`), then Font Awesome's alias vocabulary
   *   (`"cog"` -> `"gear"`), then -- if `style` is still unknown -- checks the names index:  present there
   *   => `solid`, otherwise => `brands`.  A name Font Awesome doesn't know at all resolves as `brands`;
   *   `get()` then correctly finds nothing and returns `undefined`.
   * - Last resort, word order:  a name found nowhere is tried in ANY order, if those words name exactly one
   *   icon -- `"button tablet"` -> `"tablet-button"` -- see `#reorder()`.
   * - `style`, whether passed in or inferred from `outline`, always wins over the solid/brands guess --
   *   a caller who says `{ style: "brands" }` is trusted, even for a name that also happens to exist elsewhere.
   * - A word that means different icons in the two vocabularies (`"x"`, `"warning"`, `"sign in"` ...)
   *   gets Font Awesome's meaning, unless the page opts into Fomantic's -- see `preferredNames`.
   */
  static async resolve(name: string, style?: IconStyle): Promise<IconResolved> {
    const [aliases] = await Promise.all([Icons.#loadAliases(), Icons.#loadNames()])
    const partial = Icons.#resolveAliases(name, style, aliases)
    if (partial.style === "brands") return { name: partial.name, style: "brands" }
    const found = Icons.#reorder(partial.name, aliases.fa)
    return { name: found, style: partial.style ?? (Icons.#isSolid(found) ? "solid" : "brands") }
  }

  /**
   * `name`, or the one icon its words name in another order -- `"button-tablet"` -> `"tablet-button"`.
   * - MUST have `#nameSets` loaded:  the only lookup step that needs the full name list.
   * - Only for a name the index doesn't include:  an exact name, Fomantic alias or FA alias always wins.
   * - Ambiguous word sets (`a-z` vs `z-a`, `left-right` vs `right-left`) stay as typed, so they fail loudly
   *   rather than silently picking one.
   * - NOTE: covers solid + regular (every regular icon is also solid) and brands only through FA's aliases
   *   (`github-square` -> `square-github`) -- reordering by brand names could redirect a real brand.
   *   `Icons.test.ts` checks no real brand name is ever redirected.
   */
  static #reorder(name: string, faAliases: IconAliasMap): string {
    const sets = Icons.#nameSets!
    if (!name.includes("-") || sets.solid.has(name) || sets.brands.has(name)) return name
    Icons.#wordSets ??= Icons.#buildWordSets(sets.solid, faAliases)
    return Icons.#wordSets.get(Icons.#wordSet(name)) ?? name
  }

  /** `#wordSets` from every multi-word solid name and Font Awesome alias. */
  static #buildWordSets(solid: ReadonlySet<string>, faAliases: IconAliasMap): Map<string, string | null> {
    const sets = new Map<string, string | null>()
    const entries = [...[...solid].map((key) => [key, key]), ...Object.entries(faAliases)]
    for (const [key, target] of entries) {
      if (!key.includes("-")) continue
      const words = Icons.#wordSet(key)
      const current = sets.get(words)
      sets.set(words, current === undefined || current === target ? target : null)
    }
    return sets
  }

  /** Order-free key for a dashed name:  its words, sorted -- `"tablet-button"` -> `"button tablet"`. */
  static #wordSet(name: string): string {
    return name.split("-").sort().join(" ")
  }

  /**
   * The synchronous, cache-only half of `resolve()` -- alias lookups only, no chunk loading.
   * - Shared by `get()` / `resolve()` (which await `#loadAliases()` first, so `aliases` is always populated
   *   there) and `peek()` (which passes whatever's already cached -- `undefined` maps just fall through to
   *   the dashed name unchanged, same as a name with no alias at all).
   */
  static #resolveAliases(
    name: string,
    style: IconStyle | undefined,
    aliases: AliasMaps | undefined
  ): { name: string; style?: IconStyle } {
    const words = Icons.#words(name)
    let resolvedStyle = style
    if (!resolvedStyle && words.at(-1) === "outline") {
      resolvedStyle = "regular"
      words.pop()
    }
    const phrase = words.join(" ")
    const kebab = words.join("-")
    const clash = aliases && Icons.preferredNames === "fomantic" ? aliases.fomanticClashes[phrase] : undefined
    const afterFomantic = clash ?? aliases?.fomantic[phrase] ?? kebab
    const canonical = aliases?.fa[afterFomantic] ?? afterFomantic
    return { name: canonical, style: resolvedStyle }
  }

  /**
   * Which vocabulary wins a clash, read from `<html ui-icon-names>` on EVERY lookup.
   * - `"fontawesome"` unless the attribute says `"fomantic"`;  also outside a browser (no `document`).
   * - NOTE: flipping the attribute affects later lookups only -- icons already drawn keep their old meaning.
   */
  static get preferredNames(): IconNames {
    if (typeof document === "undefined") return "fontawesome"
    return document.documentElement.getAttribute(ICON_NAMES_ATTRIBUTE) === "fomantic" ? "fomantic" : "fontawesome"
  }

  ////////////////
  // ## Data access
  ////////////////

  /**
   * Resolves `name` and loads its glyph module (once per icon, cached after), returning its
   * `[width, height, path]` tuple -- `undefined` for a name Font Awesome doesn't have in that style.
   * - Order, each step only if the one before found nothing:
   *   - explicit `style`:  the name as typed, in that style -- one request
   *   - exact Font Awesome name (no alias maps yet):  solid, then brands
   *   - aliases + `outline`, then the result in its style, or solid, then brands
   *   - word order (`"button tablet"`), the one step that loads `names.json`
   * - An explicit style never probes another style.
   * - Never rejects:  a failed import is a miss (see `#loadGlyph()`).
   */
  static async get(name: string, style?: IconStyle): Promise<IconData | undefined> {
    const kebab = Icons.#kebab(name)
    // An explicit style is trusted BEFORE aliasing:  `("apple", "brands")` means the Apple logo, not the
    // Fomantic alias `apple` -> `apple-whole` (solid), which has no brands entry at all.
    if (style) {
      const plain = await Icons.#lookup(kebab, style)
      if (plain) return plain
    }
    // Fast path:  an exact Font Awesome name needs no alias maps (~12 KB gzip), because in the default
    // vocabulary an exact name always resolves to itself.  Skipped:
    // - once the maps are cached:  they then route an alias name with no 404s, and an exact name unchanged
    // - in Fomantic mode, which can remap an exact name (`x`)
    // - for a trailing `outline`, which no Font Awesome name has
    if (!style && !Icons.#aliases && Icons.preferredNames !== "fomantic" && Icons.#words(name).at(-1) !== "outline") {
      const exact = await Icons.#find(kebab)
      if (exact) return exact
    }
    const aliases = await Icons.#loadAliases()
    const partial = Icons.#resolveAliases(name, style, aliases)
    const found = await Icons.#find(partial.name, partial.style)
    if (found || partial.style === "brands" || !partial.name.includes("-")) return found
    // last resort, word order:  the one step that needs the whole name list
    await Icons.#loadNames()
    const reordered = Icons.#reorder(partial.name, aliases.fa)
    return reordered === partial.name ? undefined : Icons.#find(reordered, partial.style)
  }

  /**
   * Registers a statically imported glyph, so `get()` / `peek()` answer for it without any request.
   * - The tree-shakable path:  `import user from "@spell/ui/icons/glyphs/solid/user.js"` +
   *   `Icons.register("user", user)` bundles just that icon.
   * - Also how an app adds its OWN icon:  any `name` works, it needn't exist in Font Awesome.
   * - Replaces whatever was loaded, registered or recorded missing under the same `name` + `style`;
   *   `name` is normalized like a lookup (`"Circle Check"` ~== `"circle-check"`), but not aliased.
   * - SIDE EFFECT:  shared page-wide cache, there is no unregister.
   */
  static register(name: string, data: IconData, style: IconStyle = "solid"): void {
    Icons.#icons.set(`${style}/${Icons.#kebab(name)}`, { promise: Promise.resolve(data), data })
  }

  /**
   * `name` in `style`, or -- no style -- whatever's already cached, then solid, then brands.
   * - Cache first, so a `register()`ed brand or regular icon costs no request.
   * - NOTE: `font-awesome` / `web-awesome` exist in BOTH solid and brands:  a style-less lookup gets solid,
   *   unless the brand is already cached (explicit `get(name, "brands")`) and solid isn't.
   */
  static async #find(name: string, style?: IconStyle): Promise<IconData | undefined> {
    if (style) return Icons.#lookup(name, style)
    return Icons.#cached(name) ?? (await Icons.#lookup(name, "solid")) ?? (await Icons.#lookup(name, "brands"))
  }

  /**
   * The glyph behind `get()`:  the cached or freshly imported tuple of `name` in `style`, if that icon exists.
   * - Requests only a safe slug (`GLYPH_NAME`), and nothing the names index (if loaded) rules out.
   */
  static async #lookup(name: string, style: IconStyle): Promise<IconData | undefined> {
    const cached = Icons.#icons.get(`${style}/${name}`)
    if (cached) return cached.promise
    if (!GLYPH_NAME.test(name)) return undefined
    if (Icons.#nameSets && !Icons.#nameSets[style].has(name)) return undefined
    return Icons.#loadGlyph(name, style)
  }

  /**
   * Already-loaded data for `name`:  in `style`, or -- no style -- in solid, brands, then regular.
   * - Synchronous:  what `peek()` answers with, and `#find()`'s cache-first step.
   */
  static #cached(name: string, style?: IconStyle): IconData | undefined {
    const styles: readonly IconStyle[] = style ? [style] : ["solid", "brands", "regular"]
    for (const each of styles) {
      const data = Icons.#icons.get(`${each}/${name}`)?.data
      if (data) return data
    }
    return undefined
  }

  /** `name`'s words, lowercased, split on spaces AND dashes -- `"Circle  Check"` -> `["circle", "check"]`. */
  static #words(name: string): string[] {
    return name
      .trim()
      .toLowerCase()
      .split(/[\s-]+/)
      .filter(Boolean)
  }

  /** `name` normalized the way the glyph files spell it:  lowercase words joined with `-`. */
  static #kebab(name: string): string {
    return Icons.#words(name).join("-")
  }

  /**
   * Whether `name` is a solid icon:  in the names index, or `register()`ed as solid.
   * - `#nameSets` MUST be loaded when `resolve()` calls this.
   */
  static #isSolid(name: string): boolean {
    return Icons.#nameSets?.solid.has(name) === true || Icons.#icons.has(`solid/${name}`)
  }

  /**
   * Synchronous counterpart to `get()`:  returns the tuple if that icon has ALREADY been loaded (by an
   * earlier `get()` or `preload()`) or `register()`ed, `undefined` otherwise -- never triggers a fetch itself.
   * - Uses only the synchronous alias/style resolution:  if the style is still ambiguous (no explicit
   *   `style`, no `outline` word) it looks for the name cached as `solid`, then `brands`, then `regular`.
   * - Word order (`"button tablet"`) only once `names.json` AND the alias maps are cached -- before that
   *   there's nothing to reorder against.
   */
  static peek(name: string, style?: IconStyle): IconData | undefined {
    if (style) {
      // same explicit-style-first rule as `get()`
      const plain = Icons.#cached(Icons.#kebab(name), style)
      if (plain) return plain
    }
    const partial = Icons.#resolveAliases(name, style, Icons.#aliases)
    const direct = Icons.#cached(partial.name, partial.style)
    if (direct || partial.style === "brands" || !Icons.#nameSets || !Icons.#aliases) return direct
    const reordered = Icons.#reorder(partial.name, Icons.#aliases.fa)
    return reordered === partial.name ? undefined : Icons.#cached(reordered, partial.style)
  }

  /**
   * Warms the cache for `names` (each resolved with its default style), plus the alias maps --
   * fire-and-forget from a component, or from a parent list before rendering slotted icons.
   * - Warming the alias maps explicitly (not just as a side effect of `get()`) means `preload([])` still
   *   readies `peek()` for Fomantic / Font Awesome aliases.
   * - NOT `names.json`:  exact names don't need it, and a word-order name loads it through `get()`.
   */
  static async preload(names: readonly string[]): Promise<void> {
    await Promise.all([Icons.#loadAliases(), ...names.map((name) => Icons.get(name))])
  }

  /**
   * Every icon name available in `style`, sorted, for the docs site's icon browser.
   * - `async` because the names index is lazy (`names.json`, ~29 KB, ~9 KB gzip).
   * - SIDE EFFECT:  once loaded, the index also saves `get()` its 404s for names it rules out.
   * - Font Awesome's names only:  `register()`ed icons are not listed.
   */
  static async names(style: IconStyle): Promise<string[]> {
    return [...(await Icons.#loadNames())[style]]
  }

  ////////////////
  // ## Lazy data loading
  ////////////////

  /**
   * Loads (once) and caches the three alias maps -- `aliases.json` (Font Awesome's own), `fomantic-aliases.json`
   * and `fomantic-clashes.json`.  `peek()` instead reads `#aliases` straight from cache, `undefined` until
   * this has resolved at least once.
   * - Literal specifiers (not a template):  each file becomes its own lazy chunk instead of landing in the
   *   eager bundle of every component that renders an icon.
   */
  static async #loadAliases(): Promise<AliasMaps> {
    Icons.#aliasesLoader ??= Promise.all([
      import("./data/aliases.json"),
      import("./data/fomantic-aliases.json"),
      import("./data/fomantic-clashes.json")
    ]).then(([fa, fomantic, fomanticClashes]) => {
      const maps: AliasMaps = {
        fa: fa.default as IconAliasMap,
        fomantic: fomantic.default as IconAliasMap,
        fomanticClashes: fomanticClashes.default as IconAliasMap
      }
      Icons.#aliases = maps
      return maps
    })
    return Icons.#aliasesLoader
  }

  /**
   * Loads (once) and caches `names.json`, plus its `Set` form.
   * - Only for `names()`, `resolve()` and the word-order fallback -- NEVER on `get()`'s direct path.
   */
  static async #loadNames(): Promise<IconNamesIndex> {
    Icons.#namesLoader ??= import("./data/names.json").then((module) => {
      const names = module.default as IconNamesIndex
      Icons.#nameSets = {
        solid: new Set(names.solid),
        regular: new Set(names.regular),
        brands: new Set(names.brands)
      }
      return names
    })
    return Icons.#namesLoader
  }

  /**
   * Imports (once) `glyphs/<style>/<name>.js`, resolving `undefined` if it doesn't exist.
   * - The URL is computed, and `import()` is `@vite-ignore`d:  a bundler must NOT see a pattern here, or it
   *   would emit (or inline) every glyph.  `#lookup()` only passes a `GLYPH_NAME` slug.
   * - A failed import is recorded as a MISS (entry kept, no `data`):  that URL is never requested again.
   *   - `import()` rejects the same way for a 404 and a dropped connection -- no status to tell them apart
   *   - the one cheap signal is `navigator.onLine === false`:  then the entry is forgotten, so a later
   *     `get()` retries.  Glyphs not deployed at all => every icon a miss, until reload.
   */
  static #loadGlyph(name: string, style: IconStyle): Promise<IconData | undefined> {
    const key = `${style}/${name}`
    const url = new URL(`glyphs/${key}.js`, Icons.glyphBase || Icons.#moduleUrl).href
    // NOTE: `entry` is built before `promise` so the `.then()` closure can fill in `entry.data` once the
    // import settles -- `peek()` reads that same object back out of `#icons`, no separate bookkeeping.
    const entry = {} as IconEntry
    entry.promise = import(/* @vite-ignore */ url).then(
      (module: { default: IconData }) => (entry.data = module.default),
      () => {
        if (typeof navigator !== "undefined" && navigator.onLine === false) Icons.#icons.delete(key)
        return undefined
      }
    )
    Icons.#icons.set(key, entry)
    return entry.promise
  }

  /** URL of the module containing `Icons` -- the default place to look for `glyphs/`.  Own getter so the bundler leaves it alone. */
  static get #moduleUrl(): string {
    return import.meta.url
  }

  ////////////////
  // ## Rendering
  ////////////////

  /**
   * Builds an `<svg>` element for `data` (from `get()` / `peek()`):  its `viewBox` plus a single
   * `<path fill="currentColor">`, so CSS `color` drives the icon's colour same as text.
   * - No `label` (the common case, a purely decorative icon next to visible text) => `aria-hidden="true"`,
   *   so screen readers skip it.
   * - A `label` => `role="img"` + `aria-label`, making the icon itself the accessible name (for an icon-only
   *   control with no visible text).
   * - `title` adds an `<svg><title>` for a native tooltip -- independent of `label`, since a labelled icon
   *   can still want hover text.
   */
  static svg(data: IconData, options: { label?: string; title?: string } = {}): SVGSVGElement {
    const [width, height, path] = data
    const svg = document.createElementNS(SVG_NS, "svg")
    svg.setAttribute("viewBox", `0 0 ${width} ${height}`)
    if (options.label) {
      svg.setAttribute("role", "img")
      svg.setAttribute("aria-label", options.label)
    } else {
      svg.setAttribute("aria-hidden", "true")
    }
    if (options.title) {
      const title = document.createElementNS(SVG_NS, "title")
      title.textContent = options.title
      svg.append(title)
    }
    const path_ = document.createElementNS(SVG_NS, "path")
    path_.setAttribute("fill", "currentColor")
    path_.setAttribute("d", path)
    svg.append(path_)
    return svg
  }

  /**
   * `svg()`'s string equivalent, for templating into `innerHTML` -- e.g. a component's shadow-root template
   * literal, where creating a live element up front would be wasted work.
   * - Always `aria-hidden`:  a templated icon has no `label`/`title` slot -- a caller that needs those
   *   builds with `svg()` instead, or wraps the string in its own labelled container.
   * - Path data is digits / letters / spaces / punctuation only (SVG path grammar), never a quote or `<` --
   *   safe to inline without escaping.
   */
  static svgString(data: IconData): string {
    const [width, height, path] = data
    return `<svg viewBox="0 0 ${width} ${height}" aria-hidden="true"><path fill="currentColor" d="${path}"/></svg>`
  }
}

/** The three alias maps `#loadAliases()` loads together, cached as one unit on `Icons.#aliases`. */
type AliasMaps = {
  /** `aliases.json` -- Font Awesome's own alternate names. */
  fa: IconAliasMap
  /** `fomantic-aliases.json` -- Fomantic's vocabulary, where it differs from FA7 and doesn't clash. */
  fomantic: IconAliasMap
  /** `fomantic-clashes.json` -- Fomantic names that clash with a Font Awesome one;  opt-in only. */
  fomanticClashes: IconAliasMap
}
