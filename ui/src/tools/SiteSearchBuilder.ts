import { parseHTML } from "linkedom"

import { PageOutline } from "spell/ui/components/ui-toc/PageOutline"
import { SpellUIGuide } from "spell/ui/util/SpellUIGuide"
import type { SiteDataFile, SiteSearchFile, SiteSearchPage } from "spell/ui/docs-components/docs-components.types"

/****************
 * ### `SiteSearchBuilder`
 * Builds a site's search file, `docs/__data/search.json5` (`SiteSearchFile`):
 * every page's title and sections, for `<ui-docs-search>`'s jumps to other pages.
 * - Spell UI's:  from its Spell pages AS THEY'RE DRAWN, which `yarn site:check --all` reads as it walks the site
 *   (`SiteCheck`, `spellSite()`):  each page its address (`/button/api`), each section its id as the contents gave it.
 *   - Rerun `yarn site:check --all` (or `--search`, which only reads) after adding, renaming or moving a section.
 * - Until epic `editor` P44 it also read the other sets' HTML pages (Epic UI's, App UI's), for their `yarn site:data`:
 *   gone with those pages.
 * - What a section is, its title, parent and tab:  `PageOutline.sections()`.
 *   - The SAME rules the element reads the page shown with, run here on linkedom (a DOM in node), read only.
 * - A component's Usage page names the tag it documents:  the search lists it as that component, not as a page.
 * - Deterministic:  pages in the site's order, sections in document order, no dates.
 ****************/
export class SiteSearchBuilder {
  /**
   * `file` as `search.json5`'s text:  2-space JSON, but ONE section per line (a third of the size, and a diff still
   * names the section that changed).
   */
  static textOf(file: SiteSearchFile): string {
    const pages = file.pages.map((page) => {
      const { sections, ...head } = page
      const fields = Object.entries(head).map(
        ([key, value]) => `      ${JSON.stringify(key)}: ${JSON.stringify(value)}`
      )
      const lines = sections.map((section) => `        ${JSON.stringify(section)}`)
      const list = lines.length ? `[\n${lines.join(",\n")}\n      ]` : "[]"
      return `    {\n${[...fields, `      "sections": ${list}`].join(",\n")}\n    }`
    })
    return `{\n  "$comment": ${JSON.stringify(file.$comment)},\n  "pages": [\n${pages.join(",\n")}\n  ]\n}\n`
  }

  ////////////////
  // ## Spell UI's Spell pages
  ////////////////

  /**
   * The Spell UI site's search file, from its pages as `yarn site:check` drew them (in the site's order).
   * - `data`:  the site's `components.json5`, which names the tag each family's Usage page documents
   *   (`SpellUIGuide.siteAddressOf()` of its old page).
   */
  static spellSite(pages: readonly DrawnSpellPage[], data: SiteDataFile): SiteSearchFile {
    const tags = new Map<string, string>()
    for (const tag of data.components) {
      if (tag.page && tag.href) tags.set(SpellUIGuide.siteAddressOf(tag.href.replace(/[?#].*$/, "")), tag.tag)
    }
    return {
      $comment:
        "GENERATED by `yarn site:check --all` (ui/scripts/site-check.ts, src/tools/SiteCheck.ts) from the Spell UI " +
        "site's pages as they're drawn (@spell/guides/SpellUI) -- do not edit.  Shape:  `SiteSearchFile` in " +
        "src/docs-components/docs-components.types.ts.",
      pages: pages.map((page) => SiteSearchBuilder.spellPage(page, tags.get(page.address)))
    }
  }

  /**
   * One Spell page's entry, from the markup it drew (`DrawnSpellPage`):
   * its sections (`PageOutline.sections()`), its title's sub header as its summary;
   * `tag`:  the tag it documents, a family's Usage page.
   */
  static spellPage({ address, title, html }: DrawnSpellPage, tag?: string): SiteSearchPage {
    const { document } = parseHTML(`<!doctype html><html><body>${html}</body></html>`)
    const { sections, tabs } = PageOutline.sections(document.body as unknown as Element)
    const summary = document.querySelector(SUMMARY)?.textContent?.replace(/\s+/g, " ").trim()
    return {
      path: address,
      title,
      ...(summary && { summary }),
      ...(tag && { tag }),
      ...(Object.keys(tabs).length && { tabs }),
      sections
    }
  }

  /**
   * Each page's title, by address, from the site's navigation (`<ui-site-nav pages>`, as the site draws it):
   * its name, after its parent's (`Button › API`), so the four pages of a family tell apart.
   * - `pages` unchecked:  anything that isn't a page (an object with a text `title`) is left out.
   */
  static spellTitles(pages: unknown, parent?: string, titles = new Map<string, string>()): Map<string, string> {
    for (const page of Array.isArray(pages) ? pages : []) {
      if (!page || typeof page !== "object" || typeof page.title !== "string") continue
      const title = parent ? `${parent}${TRAIL}${page.title}` : page.title
      if (typeof page.href === "string") titles.set(page.href, title)
      SiteSearchBuilder.spellTitles(page.pages, parent ?? page.title, titles)
    }
    return titles
  }
}

/** One Spell UI site page as drawn:  what `yarn site:check` reads off it (`SiteCheck`), for `spellPage()`. */
export type DrawnSpellPage = {
  /** its address on the site, `/button/api` */
  readonly address: string
  /** its title, `Button › API` (`spellTitles()`) */
  readonly title: string
  /** the markup it drew:  its page layout's page (`TocIndex.layoutPage()`), with the ids its contents gave */
  readonly html: string
}

/** A Spell page's summary:  its title's sub header (`<header level="1"> ... <header>...</></>`). */
const SUMMARY = 'ui-header[level="1"] > ui-header'

/** Between a page's title and its parent's:  as the search's results show where a section is (`TRAIL`). */
const TRAIL = " › "


