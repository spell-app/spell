import { join } from "node:path"

import { SRV } from "spell/server"
import type { AttributeSpec, ComponentVocabulary } from "spell/ui/vocabulary"
import { VocabularyFiles } from "spell/element-tools/VocabularyFiles"
import type { GeneratedOutput } from "spell/element-tools/generatedFiles"

/****************
 * ### `DefaultsTable`
 * Every component tag's attributes, cut down to what checks a widget default:  `src/vocabulary/defaults.generated.ts`
 * (epic `language` P29).
 * - What the spell compiler reads, through the app's Spell UI pack, to check and translate an app's `<ui-defaults>`
 *   (`<es-boton apariencia="píldora"/>` => `{ "ui-button": { appearance: "pill" } }`):  each attribute's name, kind,
 *   group, values and aliases, no descriptions, so it's small enough to load wherever spell compiles.
 * - Its own attributes only:  `Vocabulary` adds the shared ones (`disabled`, `loading` ...) as it registers each.
 * - Written by `yarn site:data`, beside the editors' manifests;  `tests/tools/DefaultsTable.test.ts` fails while stale.
 * - Node only:  reads the vocabulary files (`VocabularyFiles`).
 ****************/
export class DefaultsTable {
  /** `src/vocabulary/defaults.generated.ts` under `root` (Spell UI's folder), and its text, from `componentsFolder`. */
  static async output(root: string, componentsFolder: string): Promise<GeneratedOutput> {
    const file = join(root, "src/vocabulary/defaults.generated.ts")
    const vocabularies = await VocabularyFiles.read(componentsFolder)
    return [file, await SRV.formatHTML(file, DefaultsTable.text(vocabularies.map((it) => it.vocabulary)))]
  }

  /** The file's text, for `vocabularies`, by tag. */
  static text(vocabularies: ComponentVocabulary[]): string {
    const table: Record<string, DefaultsTableAttribute[]> = {}
    for (const vocabulary of [...vocabularies].sort((a, b) => a.tag.localeCompare(b.tag))) {
      table[vocabulary.tag] = vocabulary.attributes.map(DefaultsTable.attributeOf)
    }
    return [
      "// GENERATED by `yarn site:data` (`DefaultsTable`, in `src/tools/`):  NEVER edit by hand.",
      'import type { AttributeSpec } from "spell/element/vocabulary.types"',
      "",
      "/**",
      " * Every component tag's own attributes, cut down to what checks a widget default (epic `language` P29):",
      " * the app's Spell UI pack reads it to check and translate an app's `<ui-defaults>`.",
      " */",
      "export const DEFAULTS_TABLE: Readonly<",
      '  Record<string, readonly Pick<AttributeSpec, "name" | "kind" | "group" | "values" | "aliases">[]>',
      `> = ${JSON.stringify(table)}`,
      ""
    ].join("\n")
  }

  /** `spec`, cut down. */
  private static attributeOf(spec: AttributeSpec): DefaultsTableAttribute {
    const { name, kind, group, values, aliases } = spec
    return { name, kind, ...(group && { group }), ...(values && { values }), ...(aliases && { aliases }) }
  }
}

/** One attribute in the defaults table:  an `AttributeSpec`'s names and values, no more. */
export type DefaultsTableAttribute = Pick<AttributeSpec, "name" | "kind" | "group" | "values" | "aliases">
