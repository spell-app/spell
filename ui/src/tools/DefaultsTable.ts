import { join } from "node:path"

import { SRV } from "spell/server"
import { SharedVocabulary, type AttributeSpec, type ComponentVocabulary, type PartOfSpeech } from "spell/ui/vocabulary"
import { VocabularyFiles } from "spell/element-tools/VocabularyFiles"
import type { GeneratedOutput } from "spell/element-tools/generatedFiles"

/****************
 * ### `DefaultsTable`
 * Every component tag's attributes, cut down to what checks a widget default:  `src/vocabulary/defaults.generated.ts`
 * (epic `language` P29).
 * - What the spell compiler reads, through the app's Spell UI pack, to check and translate an app's `<ui-defaults>`
 *   (`<es-boton apariencia="píldora"/>` => `{ "ui-button": { appearance: "pill" } }`):  each attribute's name, kind,
 *   group, values and aliases, no descriptions, so it's small enough to load wherever spell compiles.
 * - Its own attributes only:  `Vocabulary` adds the shared ones (`disabled`, `loading` ...) as it registers each.
 * - Written by `yarn site:data`, beside the editors' manifests;  `tests/tools/DefaultsTable.test.ts` fails while stale.
 * - And beside it, what each tag and attribute IS, `src/vocabulary/help.generated.ts` (`helpOutput()`, epic `editor`
 *   P28):  the first sentence of each description, for the spell editor's completions and hovers on a drawing's tags.
 *   A file of its own, so only an editor that asks loads it.
 * - And each tag's part of speech, `src/vocabulary/partsOfSpeech.generated.ts` (`partsOfSpeechOutput()`, epic
 *   `language` T124):  its band's colour in the bubbly look, which docs pages and the editor draw without Spell UI.
 * - Node only:  reads the vocabulary files (`VocabularyFiles`).
 ****************/
export class DefaultsTable {
  /** `src/vocabulary/defaults.generated.ts` under `root` (Spell UI's folder), and its text, from `componentsFolder`. */
  static async output(root: string, componentsFolder: string): Promise<GeneratedOutput> {
    const file = join(root, "src/vocabulary/defaults.generated.ts")
    const vocabularies = await VocabularyFiles.read(componentsFolder)
    return [file, await SRV.formatHTML(file, DefaultsTable.text(vocabularies.map((it) => it.vocabulary)))]
  }

  /** The file's text, for `vocabularies`, by tag. */
  static text(vocabularies: ComponentVocabulary[]): string {
    const table: Record<string, DefaultsTableAttribute[]> = {}
    for (const vocabulary of [...vocabularies].sort((a, b) => a.tag.localeCompare(b.tag))) {
      table[vocabulary.tag] = vocabulary.attributes.map(DefaultsTable.attributeOf)
    }
    return [
      "// GENERATED by `yarn site:data` (`DefaultsTable`, in `src/tools/`):  NEVER edit by hand.",
      'import type { AttributeSpec } from "spell/element/vocabulary.types"',
      "",
      "/**",
      " * Every component tag's own attributes, cut down to what checks a widget default (epic `language` P29):",
      " * the app's Spell UI pack reads it to check and translate an app's `<ui-defaults>`.",
      " */",
      "export const DEFAULTS_TABLE: Readonly<",
      '  Record<string, readonly Pick<AttributeSpec, "name" | "kind" | "group" | "values" | "aliases">[]>',
      `> = ${JSON.stringify(table)}`,
      ""
    ].join("\n")
  }

  /** `src/vocabulary/help.generated.ts` under `root`, and its text, from `componentsFolder`. */
  static async helpOutput(root: string, componentsFolder: string): Promise<GeneratedOutput> {
    const file = join(root, "src/vocabulary/help.generated.ts")
    const vocabularies = await VocabularyFiles.read(componentsFolder)
    return [file, await SRV.formatHTML(file, DefaultsTable.helpText(vocabularies.map((it) => it.vocabulary)))]
  }

  /** The help file's text, for `vocabularies`:  each tag's own attributes, and the shared ones once. */
  static helpText(vocabularies: ComponentVocabulary[]): string {
    const tags: Record<string, TagHelp> = {}
    const shared: Record<string, string> = {}
    for (const vocabulary of [...vocabularies].sort((a, b) => a.tag.localeCompare(b.tag))) {
      const attributes: Record<string, string> = {}
      for (const spec of vocabulary.attributes) attributes[spec.name] = firstSentence(spec.description)
      for (const spec of SharedVocabulary.attributesFor(vocabulary)) {
        if (!(spec.name in attributes)) shared[spec.name] ??= firstSentence(spec.description)
      }
      const description = vocabulary.description && firstSentence(vocabulary.description)
      // no default slot:  it holds nothing, so an editor writes it closed, `<icon/>` (epic `editor` I70)
      const isEmpty = !vocabulary.slots.some((slot) => slot.name === "")
      tags[vocabulary.tag] = {
        ...(description && { description }),
        ...(isEmpty && { empty: true as const }),
        attributes
      }
    }
    return [
      "// GENERATED by `yarn site:data` (`DefaultsTable.helpOutput()`, in `src/tools/`):  NEVER edit by hand.",
      "",
      "/**",
      " * What each tag is, and each of its own attributes:  each description's first sentence (epic `editor` P28).",
      " * - `empty`:  it holds nothing (no default slot), so an editor writes it closed, `<icon/>` (I70).",
      " */",
      "export const HELP_TABLE: Readonly<",
      "  Record<string, { description?: string; empty?: true; attributes: Readonly<Record<string, string>> }>",
      `> = ${JSON.stringify(tags)}`,
      "",
      "/** What each attribute every tag takes is (`disabled`, `loading` ...). */",
      `export const SHARED_HELP: Readonly<Record<string, string>> = ${JSON.stringify(shared)}`,
      ""
    ].join("\n")
  }

  /** `src/vocabulary/partsOfSpeech.generated.ts` under `root`, and its text, from `componentsFolder`. */
  static async partsOfSpeechOutput(root: string, componentsFolder: string): Promise<GeneratedOutput> {
    const file = join(root, "src/vocabulary/partsOfSpeech.generated.ts")
    const vocabularies = await VocabularyFiles.read(componentsFolder)
    return [file, await SRV.formatHTML(file, DefaultsTable.partsOfSpeechText(vocabularies.map((it) => it.vocabulary)))]
  }

  /** The parts-of-speech file's text:  each tag that names one (`ComponentVocabulary.partOfSpeech`), by tag. */
  static partsOfSpeechText(vocabularies: ComponentVocabulary[]): string {
    const table: Record<string, PartOfSpeech> = {}
    for (const vocabulary of [...vocabularies].sort((a, b) => a.tag.localeCompare(b.tag))) {
      if (vocabulary.partOfSpeech) table[vocabulary.tag] = vocabulary.partOfSpeech
    }
    return [
      "// GENERATED by `yarn site:data` (`DefaultsTable.partsOfSpeechOutput()`, in `src/tools/`):  NEVER edit by hand.",
      'import type { PartOfSpeech } from "spell/element/vocabulary.types"',
      "",
      "/**",
      " * Each tag's part of speech, from its vocabulary (`partOfSpeech`):  its band's colour in Spell's bubbly look",
      " * (epic `language` T124).  Small on purpose:  a docs page drawing HTML bubbly loads it, never Spell UI.",
      " */",
      `export const PARTS_OF_SPEECH: Readonly<Record<string, PartOfSpeech>> = ${JSON.stringify(table)}`,
      ""
    ].join("\n")
  }

  /** `spec`, cut down. */
  private static attributeOf(spec: AttributeSpec): DefaultsTableAttribute {
    const { name, kind, group, values, aliases } = spec
    return { name, kind, ...(group && { group }), ...(values && { values }), ...(aliases && { aliases }) }
  }
}

/** One tag in the help table:  what it is, whether it holds nothing (`empty`), and what each of its own attributes is. */
type TagHelp = { description?: string; empty?: true; attributes: Record<string, string> }

/** `text`'s first sentence, on one line:  its first paragraph up to a full stop followed by a space. */
function firstSentence(text: string): string {
  const paragraph = text
    .split(/\n\s*\n/)[0]!
    .replace(/\s+/g, " ")
    .trim()
  return /^.*?[.!?](?=\s|$)/.exec(paragraph)?.[0] ?? paragraph
}

/** One attribute in the defaults table:  an `AttributeSpec`'s names and values, no more. */
export type DefaultsTableAttribute = Pick<AttributeSpec, "name" | "kind" | "group" | "values" | "aliases">
