import { themeTree } from "./styles.en"
import type {
  GeneratedDeclaration,
  ThemeData,
  ThemeLeaf,
  ThemeTokenPair,
  ThemeTree,
  ThemeValuePair
} from "./styles.types"

/****************
 * ### `ThemeFile`
 * One theme file, `<name>.theme.json5` (or a palette, `palettes/<name>.palette.json5`), turned into its sheet
 * (epic `debut` P18).
 * - A theme file holds a theme's VALUES, in `themeTree`'s nested groups, and names what it builds on:
 *   - `extends`:  the theme it builds on (Fruity:  `"glass"`), whose sheet its own imports first
 *   - `palette`:  the hues it borrows (`"apple"`)
 *   - `rules`:  its rules sheets, `themes/rules/<name>.css`:  what values can't say (selectors, the glass blur, motion)
 *   - two open groups:  `components` (a family's own tokens, by its name) and `own` (the theme's private ones)
 * - The sheet:  a first line saying it's generated, the imports (what it extends, its palette, its rules sheets),
 *   then its values on `:root`, in `@layer ui.theme`.
 *   - Its values in the FILE's order;  each `{ light, dark }` pair as `light-dark()`, or as the two tokens of a pair leaf.
 *   - So nothing that loads a theme changes:  `UI.themes` reads the folder's sheets, as before.
 * - Checks every name against `themeTree`, and throws a `TypeError` naming the file, the name and where it belongs:
 *   a name not in the tree, a family token that is a tree leaf, an `own` name that isn't the theme's,
 *   a theme it extends or a palette that doesn't exist.
 * - Colours are hex, `#rrggbb` or `#rrggbbaa`, never `rgb()`:  a plain `rgb(r g b / a)` is refused, naming the hex
 *   to write (Owen, epic `debut` P20:  "can you do colors as `#rrggbbaa`").  Relative colours (`oklch(from ...)`),
 *   `color-mix()` and `var()` are fine.
 * - PURE:  data in, text out, no file system and no JSON5 reader (the caller parses the file), so it runs in node
 *   (`yarn gen:styles`, the committed sheets) and in the browser (the test that keeps them current, the theme
 *   editor rewriting its sheet live, saved themes).
 * - Imports only its own folder's vocabulary and types:  never the element layer, nor the `spell-ui/styles` barrel
 *   with its `?inline` sheets (as `StyleGenerator`).
 ****************/
export class ThemeFile {
  /** its name:  `glass`, `apple` */
  readonly name: string

  /** a theme, in the themes folder, or a palette, in its `palettes/` */
  readonly kind: ThemeFileKind

  /** the file, parsed */
  readonly data: ThemeData

  /** every theme file by name, for what this one extends */
  private readonly themes: Readonly<Record<string, ThemeData>>

  /** every palette file by name, for the palette this one borrows */
  private readonly palettes: Readonly<Record<string, ThemeData>>

  constructor({ name, data, kind = "theme", themes = {}, palettes = {} }: ThemeFileProps) {
    this.name = name
    this.data = data
    this.kind = kind
    this.themes = themes
    this.palettes = palettes
  }

  /** The file's own name:  `glass.theme.json5`, `apple.palette.json5`. */
  get fileName(): string {
    return `${this.name}.${this.kind}.json5`
  }

  /** Where its sheet goes, from the themes folder:  `glass.css`, `palettes/apple.css`. */
  get sheetPath(): string {
    return this.kind === "palette" ? `${PALETTES}/${this.name}.css` : `${this.name}.css`
  }

  ////////////////
  // ## The sheet
  ////////////////

  /**
   * The theme's sheet, as CSS text.
   * - throws a `TypeError` on a mistake in the file (see the class docs)
   */
  css(): string {
    const declarations = this.declarations()
    const imports = this.imports().map((path) => `@import "${path}";`)
    return [
      `/* GENERATED by \`yarn gen:styles\` from \`${this.fileName}\`:  edit that file, never this sheet. */`,
      "",
      ...(imports.length ? [...imports, ""] : []),
      "@layer ui.theme {",
      "  :root {",
      ...declarations.map(([token, value]) => `    ${token}: ${value};`),
      "  }",
      "}",
      ""
    ].join("\n")
  }

  /**
   * The theme as a sheet WORN OVER what it extends, already on the page:  its own values on `:root`, in
   * `@layer ui.app`, and no imports.
   * - What the theme editor makes (`<ui-theme-editor>`, epic `debut` P24):  the page applies the base theme
   *   (`UI.themes.apply()`), then this.
   * - `ui.app`, not `ui.theme`:  a later layer wins however the sheets arrive (the base's may load after it).
   * - `important`:  every value `!important`, for a page whose own sheets set tokens outside any layer
   *   (the theme editor's framed pages, the editor app).
   * - `comments`:  lines for the comment at its top (the theme's name, its base).
   * - Nothing of its own:  `comments` alone, no rule.
   * - throws a `TypeError` on a mistake in the file (see the class docs)
   */
  overlayCss({ important = false, comments = [] }: { important?: boolean; comments?: readonly string[] } = {}): string {
    const declarations = this.declarations()
    const head = comments.length ? `/* ${comments.join("\n   ")} */\n` : ""
    if (!declarations.length) return head
    const mark = important ? " !important" : ""
    const body = declarations.map(([token, value]) => `    ${token}: ${value}${mark};`).join("\n")
    return `${head}@layer ui.app {\n  :root {\n${body}\n  }\n}\n`
  }

  /**
   * Its sheet's `@import`s, relative to the sheet, in order:  what it extends, its palette, its rules sheets.
   * - throws a `TypeError` when the theme it extends or its palette has no file
   */
  imports(): string[] {
    const { extends: base, palette, rules = [] } = this.data
    const up = this.kind === "palette" ? "../" : "./"
    if (this.kind === "palette" && (base || palette))
      this.fail("a palette builds on nothing:  no `extends`, no `palette`")
    if (base) this.themeData(base)
    if (palette) this.paletteData(palette)
    return [
      ...(base ? [`./${base}.css`] : []),
      ...(palette ? [`./${PALETTES}/${palette}.css`] : []),
      ...rules.map((rule) => `${up}${RULES}/${rule}.css`)
    ]
  }

  /**
   * Its OWN values, as declarations, in the file's order:  not what it extends, nor its palette.
   * - throws a `TypeError` on a mistake in the file (see the class docs)
   */
  declarations(): GeneratedDeclaration[] {
    const out: GeneratedDeclaration[] = []
    for (const [key, value] of Object.entries(this.data)) {
      if (META_KEYS.has(key)) continue
      if (key === COMPONENTS) this.componentDeclarations(value, out)
      else if (key === OWN) this.ownDeclarations(value, out)
      else this.groupDeclarations(value, themeTree, [key], out)
    }
    return out
  }

  /**
   * Every value the theme ends with, token => CSS text:  what it extends, its palette, then its own, later ones winning.
   * - What its rules sheets set is left out:  they're CSS.
   * - throws a `TypeError` on a mistake in any of the files, or a theme that extends itself
   */
  values(seen: ReadonlySet<string> = new Set()): Map<string, string> {
    if (seen.has(this.name)) this.fail(`it extends itself, through ${[...seen].join(" > ")}`)
    const values = new Map<string, string>()
    const { extends: base, palette } = this.data
    const inherited = [
      ...(base ? [this.sibling(base, "theme", this.themeData(base))] : []),
      ...(palette ? [this.sibling(palette, "palette", this.paletteData(palette))] : [])
    ]
    for (const file of inherited)
      for (const [token, value] of file.values(new Set([...seen, this.name]))) values.set(token, value)
    for (const [token, value] of this.declarations()) values.set(token, value)
    return values
  }

  ////////////////
  // ## The groups
  ////////////////

  /** Declarations of `values`, a theme file's group at `path`, against `tree`, the tree's group there. */
  private groupDeclarations(values: unknown, tree: ThemeTree, path: string[], out: GeneratedDeclaration[]) {
    const node = tree[path.at(-1)!]
    if (node === undefined) {
      this.fail(`\`${path.join(".")}\` is no name in the theme tree;  ${this.holds(tree, path.slice(0, -1))}`)
    }
    if (ThemeFile.isLeaf(node)) {
      out.push(...this.leafDeclarations(node, values, path))
      return
    }
    if (!ThemeFile.isGroup(values)) {
      this.fail(`\`${path.join(".")}\` is a group, not a value;  ${this.holds(node, path)}`)
    }
    for (const [key, value] of Object.entries(values)) this.groupDeclarations(value, node, [...path, key], out)
  }

  /** Declarations of `value`, set at `path`, a tree leaf whose token(s) are `leaf`. */
  private leafDeclarations(leaf: ThemeLeaf, value: unknown, path: string[]): GeneratedDeclaration[] {
    const text = this.valueText(value, path)
    if (typeof leaf === "string") {
      return [[leaf, typeof text === "string" ? text : `light-dark(${text.light}, ${text.dark})`]]
    }
    return [
      [leaf.light, typeof text === "string" ? text : text.light],
      [leaf.dark, typeof text === "string" ? text : text.dark]
    ]
  }

  /** `components`:  each family's tokens, `--ui-<family>-<name>`;  a tree leaf's token is refused, naming its place. */
  private componentDeclarations(families: unknown, out: GeneratedDeclaration[]) {
    for (const [family, tokens] of this.entriesOf(families, [COMPONENTS])) {
      for (const [name, value] of this.entriesOf(tokens, [COMPONENTS, family])) {
        const token = `--ui-${family}-${name}`
        const place = TREE_PLACES.get(token)
        if (place) this.fail(`\`${COMPONENTS}.${family}.${name}\` sets ${token}, which belongs in \`${place}\``)
        out.push(...this.leafDeclarations(token, value, [COMPONENTS, family, name]))
      }
    }
  }

  /** `own`:  the theme's private tokens, `--<name>`, each named for the theme or one it builds on (`glass-blur`). */
  private ownDeclarations(tokens: unknown, out: GeneratedDeclaration[]) {
    const owners = this.owners()
    for (const [name, value] of this.entriesOf(tokens, [OWN])) {
      if (!owners.some((owner) => name.startsWith(`${owner}-`))) {
        this.fail(
          `\`${OWN}.${name}\` isn't the theme's:  its name starts with ${owners.map((owner) => `\`${owner}-\``).join(" or ")}`
        )
      }
      out.push(...this.leafDeclarations(`--${name}`, value, [OWN, name]))
    }
  }

  /** The names an `own` token may start with:  this theme's, and those of the themes it builds on. */
  private owners(): string[] {
    const owners = [this.name]
    for (let base = this.data.extends; base && !owners.includes(base); base = this.themes[base]?.extends)
      owners.push(base)
    return owners
  }

  ////////////////
  // ## Values
  ////////////////

  /** `value`, set at `path`, as CSS text:  one string, or one per scheme. */
  private valueText(value: unknown, path: string[]): string | { light: string; dark: string } {
    if (ThemeFile.isPair(value)) return { light: this.text(value.light, path), dark: this.text(value.dark, path) }
    return this.text(value, path)
  }

  /** One value as CSS text, each `{a.b}` pointer written as `var(<its token>)`. */
  private text(value: unknown, path: string[]): string {
    if (typeof value === "number") return String(value)
    if (typeof value !== "string") {
      this.fail(`\`${path.join(".")}\` is a value:  CSS text, a number, or \`{ "light": ..., "dark": ... }\``)
    }
    const rgb = PLAIN_RGB.exec(value)
    if (rgb) this.fail(`\`${path.join(".")}\` writes \`${rgb[0]}\`:  write it as hex, \`${ThemeFile.hexOf(rgb)}\``)
    return value.replace(POINTER, (_, pointer: string) => `var(${this.tokenAt(pointer, path)})`)
  }

  /** The token `pointer` (`surfaces.panel`, `components.menu.radius`, `own.glass-blur`) names, set at `path`. */
  private tokenAt(pointer: string, path: string[]): string {
    const [head, ...rest] = pointer.split(".")
    if (head === OWN && rest.length === 1) return `--${rest[0]}`
    if (head === COMPONENTS && rest.length === 2) return `--ui-${rest[0]}-${rest[1]}`
    let node: ThemeLeaf | ThemeTree | undefined = themeTree
    for (const key of pointer.split(".")) node = ThemeFile.isGroup(node) ? (node as ThemeTree)[key] : undefined
    if (typeof node === "string") return node
    this.fail(
      `\`${path.join(".")}\` points at \`{${pointer}}\`, ` +
        (node ? "a pair or a group, not one token" : "which is no name in the theme tree")
    )
  }

  ////////////////
  // ## Helpers
  ////////////////

  /** The hex of a plain `rgb()` colour `PLAIN_RGB` matched:  `rgb(0 0 0 / 0.3)` => `#0000004d` (its alpha `round(a × 255)`). */
  static hexOf([, ...channels]: RegExpExecArray): string {
    const [r, g, b, alpha] = channels
    const bytes = [r, g, b].map(Number)
    if (alpha !== undefined) bytes.push(Math.round(Number(alpha) * 255))
    return `#${bytes.map((byte) => byte.toString(16).padStart(2, "0")).join("")}`
  }

  /** Theme `name`'s data;  throws when there's no such theme file. */
  private themeData(name: string): ThemeData {
    const data = this.themes[name]
    if (!data) this.fail(`it extends \`${name}\`, but no \`${name}.theme.json5\` exists`)
    return data
  }

  /** Palette `name`'s data;  throws when there's no such palette file. */
  private paletteData(name: string): ThemeData {
    const data = this.palettes[name]
    if (!data) this.fail(`its palette is \`${name}\`, but no \`${PALETTES}/${name}.palette.json5\` exists`)
    return data
  }

  /** Another file of the same set:  what this one extends, or its palette. */
  private sibling(name: string, kind: ThemeFileKind, data: ThemeData): ThemeFile {
    return new ThemeFile({ name, kind, data, themes: this.themes, palettes: this.palettes })
  }

  /** `value`'s entries, a group of the file at `path`;  throws when it isn't one. */
  private entriesOf(value: unknown, path: string[]): Array<[string, unknown]> {
    if (!ThemeFile.isGroup(value)) this.fail(`\`${path.join(".")}\` is a group:  names and their values`)
    return Object.entries(value)
  }

  /** What tree group `group` (at `path`) holds, for an error. */
  private holds(group: ThemeTree, path: string[]): string {
    const where = path.length ? `\`${path.join(".")}\`` : "the top level"
    const names = Object.keys(group)
    if (!path.length) names.push(COMPONENTS, OWN)
    return `${where} holds:  ${names.join(", ")}`
  }

  /** Throw the `TypeError` for a mistake in this file. */
  private fail(problem: string): never {
    throw new TypeError(`ThemeFile:  ${this.fileName}:  ${problem}`)
  }

  /** Whether `node`, of `themeTree`, is a leaf:  a token, or a pair of them. */
  static isLeaf(node: ThemeLeaf | ThemeTree): node is ThemeLeaf {
    return typeof node === "string" || ThemeFile.isTokenPair(node)
  }

  /** Whether `node` is a `{ light, dark }` pair of tokens. */
  static isTokenPair(node: unknown): node is ThemeTokenPair {
    return ThemeFile.isPair(node)
  }

  /** Whether `value` is a `{ light, dark }` pair:  exactly those two keys. */
  static isPair(value: unknown): value is ThemeValuePair {
    if (!ThemeFile.isGroup(value)) return false
    const keys = Object.keys(value)
    return keys.length === 2 && "light" in value && "dark" in value
  }

  /** Whether `value` is a plain object, as a group is. */
  static isGroup(value: unknown): value is Record<string, unknown> {
    return typeof value === "object" && value !== null && !Array.isArray(value)
  }

  ////////////////
  // ## The schema
  ////////////////

  /**
   * `theme.schema.json`'s JSON Schema, from `themeTree`:  VS Code completes a theme file's names and flags a wrong one.
   * - `yarn gen:styles` writes it beside the themes;  each file names it (`"$schema": "./theme.schema.json"`).
   */
  static schema(): Record<string, unknown> {
    const value = { $ref: "#/definitions/value" }
    const group = (tree: ThemeTree): Record<string, unknown> => ({
      type: "object",
      additionalProperties: false,
      properties: Object.fromEntries(
        Object.entries(tree).map(([key, node]) => [key, ThemeFile.isLeaf(node) ? value : group(node)])
      )
    })
    const tree = group(themeTree)
    return {
      $schema: "http://json-schema.org/draft-07/schema#",
      title: "Spell UI theme",
      description: "A theme's values in nested groups (spell-ui's themeTree);  `yarn gen:styles` writes its sheet.",
      type: "object",
      additionalProperties: false,
      properties: {
        $schema: { type: "string" },
        title: { type: "string", description: "its name, for a theme a person names" },
        extends: { type: "string", description: "the theme it builds on" },
        palette: { type: "string", description: "the palette whose hues it borrows" },
        rules: { type: "array", items: { type: "string" }, description: "its rules sheets, in themes/rules/" },
        ...(tree.properties as object),
        components: {
          type: "object",
          description: "a family's own tokens, under its name:  menu > radius is --ui-menu-radius",
          additionalProperties: { type: "object", additionalProperties: value }
        },
        own: {
          type: "object",
          description: "the theme's private tokens:  glass-blur is --glass-blur",
          additionalProperties: value
        }
      },
      definitions: {
        value: {
          description: 'CSS text (a "{group.name}" points at another value), a number, or one per scheme',
          oneOf: [
            { type: "string" },
            { type: "number" },
            {
              type: "object",
              additionalProperties: false,
              required: ["light", "dark"],
              properties: { light: { type: ["string", "number"] }, dark: { type: ["string", "number"] } }
            }
          ]
        }
      }
    }
  }

  ////////////////
  // ## A set of files
  ////////////////

  /**
   * Every sheet of a set of theme and palette files:  its path from the themes folder (`glass.css`) => its CSS.
   * - throws a `TypeError` on a mistake in any of them
   */
  static sheets({ themes, palettes }: ThemeFileSet): Record<string, string> {
    const files = [
      ...Object.entries(palettes).map(
        ([name, data]) => new ThemeFile({ name, data, kind: "palette", themes, palettes })
      ),
      ...Object.entries(themes).map(([name, data]) => new ThemeFile({ name, data, themes, palettes }))
    ]
    return Object.fromEntries(files.map((file) => [file.sheetPath, file.css()]))
  }
}

/** A theme file's kind:  its file's middle word (`glass.theme.json5`, `apple.palette.json5`). */
export type ThemeFileKind = "theme" | "palette"

/** What `new ThemeFile()` takes. */
export type ThemeFileProps = {
  /** its name:  `glass` */
  name: string
  /** the file, parsed */
  data: ThemeData
  /** a theme (the default) or a palette */
  kind?: ThemeFileKind
  /** every theme file by name:  what it may extend */
  themes?: Readonly<Record<string, ThemeData>>
  /** every palette file by name:  what it may borrow */
  palettes?: Readonly<Record<string, ThemeData>>
}

/** A set of theme files, parsed, by name:  `ThemeFile.sheets()`. */
export type ThemeFileSet = {
  /** `<name>.theme.json5` files */
  themes: Readonly<Record<string, ThemeData>>
  /** `palettes/<name>.palette.json5` files */
  palettes: Readonly<Record<string, ThemeData>>
}

/** The open group of a family's own tokens. */
const COMPONENTS = "components"

/** The open group of the theme's private tokens. */
const OWN = "own"

/** The palettes' folder, in the themes folder. */
const PALETTES = "palettes"

/** The rules sheets' folder, in the themes folder. */
const RULES = "rules"

/** Top-level keys that say what a theme builds on, not values. */
const META_KEYS = new Set(["$schema", "title", "extends", "palette", "rules"])

/** A plain `rgb()` colour, `rgb(r g b)` or `rgb(r g b / a)`:  refused, as hex is the theme files' one spelling. */
const PLAIN_RGB = /rgba?\(\s*(\d+)\s+(\d+)\s+(\d+)\s*(?:\/\s*([\d.]+)\s*)?\)/

/** A pointer at another leaf:  `{surfaces.panel}`. */
const POINTER = /\{([\w.-]+)\}/g

/** Every token of `themeTree` => its place (`--ui-bar-background` => `surfaces.bar`):  so `components` can't set one. */
const TREE_PLACES: ReadonlyMap<string, string> = (() => {
  const places = new Map<string, string>()
  const walk = (tree: ThemeTree, path: string[]) => {
    for (const [key, node] of Object.entries(tree)) {
      if (typeof node === "string") places.set(node, [...path, key].join("."))
      else if (ThemeFile.isTokenPair(node))
        for (const token of [node.light, node.dark]) places.set(token, [...path, key].join("."))
      else walk(node, [...path, key])
    }
  }
  walk(themeTree, [])
  return places
})()
